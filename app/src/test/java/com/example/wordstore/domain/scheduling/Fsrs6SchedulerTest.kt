package com.example.wordstore.domain.scheduling

import com.google.gson.Gson
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.Instant

class Fsrs6SchedulerTest {

    private val start = Instant.parse("2022-11-29T12:30:00Z").toEpochMilli()
    private val scheduler = Fsrs6Scheduler(enableFuzz = false)

    private fun newCard(id: Long = 1L) = CardMemory(cardId = id, dueAt = start)

    private data class Vectors(val generator: String, val parameters: List<Double>, val sequences: List<Sequence>)
    private data class Sequence(val startAt: Long, val steps: List<VectorStep>)
    private data class VectorStep(
        val reviewedAt: Long,
        val rating: Int,
        val state: Int,
        val step: Int?,
        val stability: Double,
        val difficulty: Double,
        val due: Long,
        val retrievabilityAtDue: Double
    )

    @Test
    fun `replays histories generated by py-fsrs exactly`() {
        val json = javaClass.classLoader!!.getResource("fsrs_reference_vectors.json")!!.readText()
        val vectors = Gson().fromJson(json, Vectors::class.java)
        assertEquals("py-fsrs 6.3.2", vectors.generator)
        assertEquals(Fsrs6Scheduler.DEFAULT_PARAMETERS, vectors.parameters)

        var compared = 0
        vectors.sequences.forEachIndexed { sequenceIndex, sequence ->
            var card = CardMemory(cardId = sequenceIndex.toLong(), dueAt = sequence.startAt)
            sequence.steps.forEachIndexed { stepIndex, expected ->
                val where = "sequence $sequenceIndex step $stepIndex"
                val outcome = scheduler.review(card, Rating.fromValue(expected.rating), expected.reviewedAt)
                card = outcome.memory

                assertEquals("$where state", expected.state, card.state.value)
                assertEquals("$where step", expected.step, card.step)
                assertEquals("$where stability", expected.stability, card.stability!!, 1e-9)
                assertEquals("$where difficulty", expected.difficulty, card.difficulty!!, 1e-9)
                assertEquals("$where due", expected.due, card.dueAt)
                assertEquals(
                    "$where retrievability",
                    expected.retrievabilityAtDue,
                    scheduler.retrievability(card, card.dueAt),
                    1e-9
                )
                compared++
            }
        }
        assertEquals(1705, compared)
    }

    @Test
    fun `matches the published py-fsrs interval history`() {
        val ratings = listOf(3, 3, 3, 3, 3, 3, 1, 1, 3, 3, 3, 3, 3).map(Rating::fromValue)
        var card = newCard()
        var now = start
        val intervals = ratings.map { rating ->
            card = scheduler.review(card, rating, now).memory
            val days = (card.dueAt - card.lastReviewAt!!) / Fsrs6Scheduler.DAY
            now = card.dueAt
            days
        }
        assertEquals(listOf<Long>(0, 2, 11, 46, 163, 498, 0, 0, 2, 4, 7, 12, 21), intervals)
    }

    @Test
    fun `matches the published py-fsrs memory state`() {
        val ratings = listOf(1, 3, 3, 3, 3, 3).map(Rating::fromValue)
        val elapsedDays = listOf(0L, 0L, 1L, 3L, 8L, 21L)
        var card = newCard()
        var now = start
        ratings.zip(elapsedDays).forEach { (rating, days) ->
            now += days * Fsrs6Scheduler.DAY
            card = scheduler.review(card, rating, now).memory
        }
        assertEquals(53.62691, card.stability!!, 1e-4)
        assertEquals(6.3574867, card.difficulty!!, 1e-4)
    }

    @Test
    fun `new card rated good moves through both learning steps then graduates`() {
        val first = scheduler.review(newCard(), Rating.GOOD, start)
        assertEquals(CardState.LEARNING, first.memory.state)
        assertEquals(1, first.memory.step)
        assertEquals(10 * Fsrs6Scheduler.MINUTE, first.intervalMillis)

        val second = scheduler.review(first.memory, Rating.GOOD, first.memory.dueAt)
        assertEquals(CardState.REVIEW, second.memory.state)
        assertEquals(null, second.memory.step)
    }

    @Test
    fun `again in review counts a lapse and enters relearning`() {
        var card = scheduler.review(newCard(), Rating.EASY, start).memory
        assertEquals(CardState.REVIEW, card.state)
        assertEquals(0, card.lapses)

        card = scheduler.review(card, Rating.AGAIN, card.dueAt).memory
        assertEquals(CardState.RELEARNING, card.state)
        assertEquals(1, card.lapses)
        assertEquals(0, card.step)
        assertEquals(2, card.reps)
    }

    @Test
    fun `again during learning returns to the first step without a lapse`() {
        var card = scheduler.review(newCard(), Rating.GOOD, start).memory
        card = scheduler.review(card, Rating.AGAIN, card.dueAt).memory
        assertEquals(CardState.LEARNING, card.state)
        assertEquals(0, card.step)
        assertEquals(0, card.lapses)
    }

    @Test
    fun `preview equals review for every rating when fuzz is on`() {
        val fuzzing = Fsrs6Scheduler()
        var card = fuzzing.review(newCard(id = 77), Rating.EASY, start).memory
        repeat(6) {
            val now = card.dueAt
            val preview = fuzzing.preview(card, now)
            Rating.entries.forEach { rating ->
                assertEquals(preview.getValue(rating), fuzzing.review(card, rating, now))
            }
            card = preview.getValue(Rating.GOOD).memory
        }
    }

    @Test
    fun `fuzz stays inside the reference range and varies between cards`() {
        val fuzzing = Fsrs6Scheduler()
        val plain = Fsrs6Scheduler(enableFuzz = false)
        val seen = HashSet<Long>()
        for (id in 1L..200L) {
            val base = plain.review(CardMemory(id, CardState.REVIEW, null, 40.0, 5.0, start, start - 40 * Fsrs6Scheduler.DAY, 5), Rating.GOOD, start)
            val fuzzed = fuzzing.review(CardMemory(id, CardState.REVIEW, null, 40.0, 5.0, start, start - 40 * Fsrs6Scheduler.DAY, 5), Rating.GOOD, start)
            val baseDays = (base.intervalMillis / Fsrs6Scheduler.DAY).toInt()
            val days = (fuzzed.intervalMillis / Fsrs6Scheduler.DAY).toInt()
            assertTrue("$days not in ${fuzzing.fuzzRange(baseDays)}", days in fuzzing.fuzzRange(baseDays).first..fuzzing.fuzzRange(baseDays).last + 1)
            seen += fuzzed.intervalMillis
        }
        assertTrue(seen.size > 1)
    }

    @Test
    fun `short intervals are not fuzzed`() {
        val fuzzing = Fsrs6Scheduler()
        val learning = fuzzing.review(newCard(), Rating.AGAIN, start)
        assertEquals(1 * Fsrs6Scheduler.MINUTE, learning.intervalMillis)
    }

    @Test
    fun `retrievability is zero before the first review and falls with time`() {
        assertEquals(0.0, scheduler.retrievability(newCard(), start), 0.0)
        val card = scheduler.review(newCard(), Rating.EASY, start).memory
        val soon = scheduler.retrievability(card, start + Fsrs6Scheduler.DAY)
        val later = scheduler.retrievability(card, start + 30 * Fsrs6Scheduler.DAY)
        assertTrue(soon > later)
        assertNotEquals(0.0, later, 0.0)
    }

    @Test
    fun `again never produces a longer interval than good`() {
        val card = scheduler.review(newCard(), Rating.EASY, start).memory
        val preview = scheduler.preview(card, card.dueAt)
        assertTrue(preview.getValue(Rating.AGAIN).intervalMillis < preview.getValue(Rating.GOOD).intervalMillis)
        assertTrue(preview.getValue(Rating.GOOD).intervalMillis < preview.getValue(Rating.EASY).intervalMillis)
    }
}
